function tab(b, i) {
  var w = b.parentNode;
  w.querySelectorAll(".tab").forEach((t) => t.classList.remove("on"));
  b.classList.add("on");
  var ps = w.parentNode.querySelectorAll(".tp");
  ps.forEach((p, j) => p.classList.toggle("on", i == j));
}
